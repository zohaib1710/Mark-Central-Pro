const desktop=await browser.newContext({viewport:{width:1440,height:1080}});
const desktopPage=await desktop.newPage();
await desktopPage.goto('http://127.0.0.1:8000/index.html',{waitUntil:'domcontentloaded'});
await desktopPage.waitForFunction(()=>document.querySelector('.stats-section').classList.contains('is-visible'));
const counterStart=await desktopPage.evaluate(()=>[...document.querySelectorAll('[data-count-to]')].map(el=>({text:el.textContent,state:el.dataset.countState})));
if(counterStart.length!==2||counterStart.some(counter=>counter.state!=='running'))failures.push('Initially visible homepage counters did not start through the entrance observer');
const staticStart=await desktopPage.evaluate(()=>[...document.querySelectorAll('.trust-item strong:not([data-count-to])')].map(el=>({text:el.textContent,state:el.dataset.countState})));
if(staticStart.map(item=>item.text).join('|')!=='5-star|3 steps'||staticStart.some(item=>item.state))failures.push('Static homepage statistics received counter behavior');
await desktopPage.evaluate(()=>{window.__counterSamples=[...document.querySelectorAll('[data-count-to]')].map(el=>[el.textContent]);[...document.querySelectorAll('[data-count-to]')].forEach((el,index)=>new MutationObserver(()=>window.__counterSamples[index].push(el.textContent)).observe(el,{childList:true,characterData:true,subtree:true}))});
const readAnimatedValues=()=>desktopPage.evaluate(()=>[...document.querySelectorAll('[data-count-to]')].map(el=>Number(el.textContent.replace(/\D/g,''))));
const timedSamples=[];
timedSamples.push({time:0,values:await readAnimatedValues()});
await desktopPage.waitForTimeout(1000);timedSamples.push({time:1,values:await readAnimatedValues()});
await desktopPage.waitForTimeout(1000);timedSamples.push({time:2,values:await readAnimatedValues()});
await desktopPage.waitForTimeout(500);timedSamples.push({time:2.5,values:await readAnimatedValues()});
await desktopPage.waitForTimeout(1500);timedSamples.push({time:4,values:await readAnimatedValues()});
const expectedRatios=[0,.2,.4,.5,.8];
timedSamples.forEach((sample,index)=>{for(const counterIndex of [0,1]){const target=counterIndex===0?100000:180;const ratio=sample.values[counterIndex]/target;if(Math.abs(ratio-expectedRatios[index])>.1)failures.push(`Counter ${counterIndex} was off linear pace at ${sample.time}s: ${sample.values[counterIndex]}`)}});
await desktopPage.waitForFunction(()=>[...document.querySelectorAll('[data-count-to]')].every(el=>el.dataset.countState==='complete'));
const counterFinal=await desktopPage.locator('.trust-item strong').allTextContents();
if(counterFinal.join('|')!=='100,000+|5-star|180+|3 steps')failures.push(`Homepage statistics ended with incorrect values: ${counterFinal.join('|')}`);
const animationSamples=await desktopPage.evaluate(()=>window.__counterSamples.map(values=>[...new Set(values.map(value=>Number(value.replace(/\D/g,''))))]));
if(animationSamples[0].length<100||animationSamples[1].length<100)failures.push(`Large counters did not produce enough intermediate values: ${animationSamples[0].length}, ${animationSamples[1].length}`);
await desktopPage.evaluate(()=>window.scrollTo(0,document.documentElement.scrollHeight));
await desktopPage.waitForTimeout(150);
await desktopPage.evaluate(()=>document.querySelector('.trust-strip').scrollIntoView({block:'center'}));
await desktopPage.waitForTimeout(150);
const counterReturn=await desktopPage.evaluate(()=>[...document.querySelectorAll('[data-count-to]')].map(el=>({text:el.textContent,state:el.dataset.countState})));
if(counterReturn.some(counter=>counter.state!=='complete')||counterReturn.map(counter=>counter.text).join('|')!=='100,000+|180+')failures.push('Homepage counters restarted after returning to the stats strip');
await desktopPage.reload({waitUntil:'domcontentloaded'});
await desktopPage.waitForFunction(()=>[...document.querySelectorAll('[data-count-to]')].every(el=>el.dataset.countState==='running'));
const counterReload=await desktopPage.evaluate(()=>([...document.querySelectorAll('.trust-item strong')].map(el=>el.textContent)));
if(counterReload[1]!=='5-star'||counterReload[3]!=='3 steps'||counterReload[0]==='100,000+'||counterReload[2]==='180+')failures.push(`Homepage statistics did not restart correctly after reload: ${counterReload.join('|')}`);
const polish=await desktopPage.evaluate(()=>{const logo=document.querySelector('.footer-brand img');const caption=document.querySelector('.quote figcaption');return{logoFilter:getComputedStyle(logo).filter,logoWidth:logo.getBoundingClientRect().width,captionDirection:getComputedStyle(caption).flexDirection}});
if(polish.logoFilter!=='none'||polish.logoWidth<150)failures.push('Footer logo styling is not visible at desktop size');
if(polish.captionDirection!=='column')failures.push('Testimonial attribution is not stacked');
const animated=desktopPage.locator('.section-head').first();
await animated.scrollIntoViewIfNeeded();
await desktopPage.waitForTimeout(800);
if(Number(await animated.evaluate(el=>getComputedStyle(el).opacity))<.9)failures.push('Entrance animation did not reveal content');
await desktop.close();

