import { chromium } from 'playwright-core';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const executablePath='C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const browser=await chromium.launch({headless:true,executablePath});
const pages=(await readdir('.')).filter(file=>file.endsWith('.html'));
const sizes=process.argv.length>2?process.argv.slice(2).map(Number):[320,375,390,430,768,1024,1280,1440,1920];
const failures=[];

for(const width of sizes){
  const context=await browser.newContext({viewport:{width,height:900},reducedMotion:'reduce'});
  const page=await context.newPage();
  for(const file of pages){
    const errors=[];
    page.removeAllListeners('pageerror');
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(`http://127.0.0.1:8000/${file}`,{waitUntil:'domcontentloaded'});
    const metrics=await page.evaluate(()=>({scrollWidth:document.documentElement.scrollWidth,clientWidth:document.documentElement.clientWidth,h1:document.querySelectorAll('h1').length}));
    if(metrics.scrollWidth>metrics.clientWidth+1)failures.push(`${file} at ${width}px overflows by ${metrics.scrollWidth-metrics.clientWidth}px`);
    if(metrics.h1!==1)failures.push(`${file} at ${width}px has ${metrics.h1} H1 elements`);
    if(file==='index.html'){
      const homeState=await page.evaluate(()=>({card:document.querySelectorAll('.status-card').length,animated:[...document.querySelectorAll('[data-count-to]')].map(el=>el.textContent),all:[...document.querySelectorAll('.trust-item strong')].map(el=>el.textContent)}));
      if(homeState.card)failures.push(`Homepage status card remains at ${width}px`);
      if(homeState.animated.length!==2||homeState.all[1]!=='5-star'||homeState.all[3]!=='3 steps')failures.push(`Homepage static statistics changed at ${width}px: ${homeState.all.join('|')}`);
      await page.evaluate(()=>document.querySelector('.stats-section').scrollIntoView({block:'center'}));
      await page.waitForFunction(()=>document.querySelector('.stats-section').classList.contains('is-visible'));
      const reducedAfterEntrance=await page.evaluate(()=>[...document.querySelectorAll('[data-count-to]')].map(el=>({text:el.textContent,state:el.dataset.countState})));
      if(reducedAfterEntrance.some(counter=>counter.state!=='running')||reducedAfterEntrance.map(counter=>counter.text).join('|')==='100,000+|180+')failures.push(`Reduced-motion counters bypassed count-up at ${width}px: ${reducedAfterEntrance.map(counter=>counter.text).join('|')}`);
    }
    if(errors.length)failures.push(`${file} at ${width}px console: ${errors.join('; ')}`);
  }
  await context.close();
}

const autoContext=await browser.newContext({viewport:{width:1280,height:800}});
const autoPage=await autoContext.newPage();
const autoClockStart=Date.now();
await autoPage.clock.install({time:autoClockStart});
await autoPage.clock.pauseAt(autoClockStart);
for(const file of pages){
  await autoPage.goto(`http://127.0.0.1:8000/${file}`,{waitUntil:'domcontentloaded'});
  if(file==='index.html')await autoPage.locator('.hero .btn-secondary').focus();
  await autoPage.clock.fastForward(19999);
  if(await autoPage.getAttribute('#lead-modal','aria-hidden')!=='true')failures.push(`${file}: automatic modal opened before 20 seconds`);
  await autoPage.clock.fastForward(1);
  const autoState=await autoPage.evaluate(()=>{const form=document.querySelector('#lead-form');return{hidden:document.querySelector('#lead-modal').getAttribute('aria-hidden'),source:form.elements.source_page.value,service:form.elements.selected_service.value,package:form.elements.selected_package.value,started:Number(form.elements.form_started_at.value),now:Math.floor(Date.now()/1000),mainInert:document.querySelector('main').inert}});
  if(autoState.hidden!=='false')failures.push(`${file}: automatic modal did not open at 20 seconds`);
  if(autoState.source!==`/${file}`||autoState.service!==''||autoState.package!=='')failures.push(`${file}: automatic modal populated incorrect source or package fields`);
  if(Math.abs(autoState.now-autoState.started)>1)failures.push(`${file}: automatic modal did not renew form_started_at`);
  if(!autoState.mainInert)failures.push(`${file}: automatic modal did not make page content inert`);
  await autoPage.clock.fastForward(20);
  if(await autoPage.evaluate(()=>document.activeElement?.id)!=='lead-name')failures.push(`${file}: automatic modal did not focus the name field`);
  await autoPage.keyboard.press('Escape');
  if(await autoPage.getAttribute('#lead-modal','aria-hidden')!=='true')failures.push(`${file}: automatic modal did not close with Escape`);
  if(file==='index.html'&&!await autoPage.locator('.hero .btn-secondary').evaluate(el=>el===document.activeElement))failures.push('Automatic modal did not restore prior focus');
  await autoPage.clock.fastForward(60000);
  if(await autoPage.getAttribute('#lead-modal','aria-hidden')!=='true')failures.push(`${file}: automatic modal reopened during the same page view`);
}
await autoContext.close();

